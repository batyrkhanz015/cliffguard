import { mkdir, writeFile } from 'node:fs/promises';
import { PDFDocument, StandardFonts, degrees, rgb } from 'pdf-lib';

const pdf = await PDFDocument.create();
pdf.setTitle('SAMPLE - Dani Marketplace eligibility notice');
pdf.setSubject('Synthetic CliffGuard demo. Not an official notice or proof of coverage.');
pdf.setCreationDate(new Date('2026-01-01T00:00:00Z'));
pdf.setModificationDate(new Date('2026-01-01T00:00:00Z'));
const page = pdf.addPage([612, 792]);
const regular = await pdf.embedFont(StandardFonts.Helvetica);
const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
const ink = rgb(0.12, 0.15, 0.22);
const violet = rgb(0.36, 0.22, 0.72);
const text = (value: string, y: number, size = 12, font = regular) => page.drawText(value, { x: 48, y, size, font, color: ink });
page.drawRectangle({ x: 0, y: 742, width: 612, height: 50, color: violet });
page.drawText('SAMPLE / SYNTHETIC DEMO DOCUMENT', { x: 48, y: 761, size: 13, font: bold, color: rgb(1, 1, 1) });
page.drawText('SAMPLE', { x: 92, y: 320, size: 94, font: bold, color: violet, opacity: 0.09, rotate: degrees(35) });
text('Marketplace eligibility notice', 701, 23, bold);
text('Coverage year: 2026', 671, 15, bold);
text('Created for the CliffGuard demo. Not issued by HealthCare.gov.', 645, 11);
text('Household information', 599, 15, bold);
text('Example household: Dani (fictional)', 574);
text('State of residence: Texas (TX)', 551);
text('Tax household size: 4 people', 528);
text('Estimated annual household income for 2026: $105,000.00', 505);
text('Monthly plan and credit', 455, 15, bold);
text('Plan name: Sample Texas Bronze Family Plan', 430);
text('Plan metal level: Bronze', 407);
text('Monthly premium before any tax credit: $1,240.00', 384);
text('Advance premium tax credit (APTC) per month: $778.50', 361);
text('Monthly premium after the tax credit: $461.50', 338);
text('Review your information', 278, 15, bold);
text('This sample illustrates the figures on an eligibility notice.', 253);
text('It does not establish eligibility, enroll anyone, or provide tax advice.', 230);
text('A real notice may have different wording and additional information.', 207);
page.drawLine({ start: { x: 48, y: 126 }, end: { x: 564, y: 126 }, thickness: 1, color: rgb(0.8, 0.8, 0.85) });
text('SAMPLE - FICTIONAL - NOT VALID FOR COVERAGE OR TAX FILING', 102, 10, bold);
text('No real names, addresses, application IDs, or account numbers.  |  Page 1 of 1', 82, 9);
await mkdir('public/samples', { recursive: true });
await writeFile('public/samples/dani-eligibility-notice.pdf', await pdf.save());
